// 소개 페이지(any=true): 어느 단계든 이름에 맞는 아이콘을 먼저 씀
export function iconPath(id, { any = false, name } = {}) {
  const info = MINISTRY_INDEX[id];
  if (!info) return BRANCH_ICONS.worship;
  if (any || info.depth >= 2) {
    const label = name || info.node.name;
    const hit = NAME_ICONS.find(([re]) => re.test(label));
    if (hit) return hit[1];
  }
  return BRANCH_ICONS[info.branch] || BRANCH_ICONS.worship;
}
